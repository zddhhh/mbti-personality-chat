/**
 * 验证 MBTI 类型是否合法
 */
export function isValidMBTI(mbti) {
  if (!mbti || mbti.length !== 4) return false;
  const upper = mbti.toUpperCase();
  return (
    (upper[0] === 'E' || upper[0] === 'I') &&
    (upper[1] === 'S' || upper[1] === 'N') &&
    (upper[2] === 'T' || upper[2] === 'F') &&
    (upper[3] === 'J' || upper[3] === 'P')
  );
}

